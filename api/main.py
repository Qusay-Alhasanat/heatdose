# Comparison — the pitch endpoint
# --------------------------------------------------------------------


@app.get("/api/comparison", response_model=ComparisonSummary)
def get_comparison() -> ComparisonSummary:
    """
    Hyperlocal continuous tracking vs. single-check-in baseline, per
    worker and roster-wide. See docs/methodology.md's "What we
    measured" section — this compares TIME (continuous vs. one check),
    not location/zone.
    """
    try:
        mock_workers = generate_mock_workers()
        real_workers = build_real_workers(mock_workers)
        summary = comparison_summary(real_workers)
    except MissingRealDataError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc

    return ComparisonSummary(**summary)


