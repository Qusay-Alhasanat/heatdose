@app.get("/api/workers", response_model=list[WorkerStatus])
def list_workers() -> list[WorkerStatus]:
    """All workers with status, sorted by excess_dose descending."""
    try:
        # "low" is the lowest band, so this returns everyone.
        statuses = list_workers_at_risk(min_level="low")
    except MissingRealDataError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc
    return [WorkerStatus(**s) for s in statuses]


@app.get("/api/workers/{worker_id}", response_model=WorkerDetail)
def get_worker(worker_id: str) -> WorkerDetail:
    """One worker's status plus their full shift trail, for the map."""
    if worker_id not in WORKER_ROSTER:
        raise HTTPException(
            status_code=404,
            detail=f"Unknown worker_id: {worker_id!r}. "
            f"Known workers: {sorted(WORKER_ROSTER)}",
        )

    try:
        status = get_worker_status(worker_id)

        config = WORKER_ROSTER[worker_id]
        mock_shift = generate_mock_shift(
            worker_id,
            route_profile=config["profile"],
            start_hour=config["start_hour"],
        )
        real_shift = attach_real_temperatures(mock_shift)
    except UnknownWorkerError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    except MissingRealDataError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc

    return WorkerDetail(
        **status,
        shift=[ShiftPoint(**point) for point in real_shift],
    )


