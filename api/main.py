@app.get("/api/heatmap", response_model=list[HeatmapPoint])
def get_heatmap(hour: int) -> list[HeatmapPoint]:
    """Full-resolution real temperature grid for one hour, for map colouring."""
    if hour not in DEMO_HOURS:
        raise HTTPException(
            status_code=400,
            detail=f"hour must be one of {DEMO_HOURS.start}-{DEMO_HOURS.stop - 1} "
            f"(the only hours cached for the demo — no live calls are ever "
            f"made from this endpoint).",
        )

    try:
        grid = get_temperature_grid(STUDY_DATE, hour, use_cache=True)
    except FortyGuardError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc

    if not grid:
        raise HTTPException(
            status_code=503,
            detail=f"No cached data for hour {hour}. "
            f"Pull it with: uv run python data/fortyguard_client.py --pull-day",
        )

    return [HeatmapPoint(**point) for point in grid]


