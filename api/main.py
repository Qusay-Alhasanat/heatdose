@app.get("/api/cool-points", response_model=list[CoolPointCandidate])
def get_cool_points(hour: int) -> list[CoolPointCandidate]:
    """
    All candidate rest points with current temps for the given hour.

    Note (see data/cool_points.py's module docstring): these
    temperatures are synthetic (mock_data.temp_at()), not real
    FortyGuard data — a deliberate scope decision, not a bug.
    """
    if not 0 <= hour <= 23:
        raise HTTPException(status_code=400, detail="hour must be 0-23")

    candidates = get_candidates_with_current_temp(hour)
    return [CoolPointCandidate(**c) for c in candidates]


